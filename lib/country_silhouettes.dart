class CountrySilhouette extends StatelessWidget {
  final String country;
  final Color color;
  const CountrySilhouette({
    super.key,
    required this.country,
    required this.color,
  });
  @override
  Widget build(BuildContext context) => CustomPaint(
    painter: _CountrySilhouettePainter(countrySilhouettes[country]!, color),
  );
}

class _CountrySilhouettePainter extends CustomPainter {
  final List<Offset> points;
  final Color color;
  const _CountrySilhouettePainter(this.points, this.color);
  @override
  void paint(Canvas canvas, Size size) {
    final path = Path()
      ..moveTo(points.first.dx * size.width, points.first.dy * size.height);
    for (final point in points.skip(1)) {
      path.lineTo(point.dx * size.width, point.dy * size.height);
    }
    path.close();
    canvas.drawPath(
      path,
      Paint()
        ..color = color.withValues(alpha: .22)
        ..style = PaintingStyle.fill,
    );
    canvas.drawPath(
      path,
      Paint()
        ..color = color
        ..style = PaintingStyle.stroke
        ..strokeWidth = 2
        ..strokeJoin = StrokeJoin.round,
    );
  }

  @override
  bool shouldRepaint(covariant _CountrySilhouettePainter oldDelegate) =>
      oldDelegate.color != color || oldDelegate.points != points;
}
